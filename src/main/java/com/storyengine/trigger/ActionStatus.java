package com.storyengine.trigger;

/**
 * Результат выполнения одного действия триггера и правило fail-stop
 * (ТЗ §8.2).
 *
 * {@code FAILURE} останавливает дальнейшую цепочку действий текущего
 * триггера: последующие действия не выполняются, ошибка логируется.
 * {@code SUCCESS} — обычный успешный шаг. {@code SKIP} — действие не
 * применяется (например, предмет уже выдан до this), но цепочка
 * продолжается и ошибкой не считается.
 */
public enum ActionStatus {
    SUCCESS,
    FAILURE,
    SKIP
}